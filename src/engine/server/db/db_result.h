#ifndef ENGINE_SERVER_DB_DB_RESULT_H
#define ENGINE_SERVER_DB_DB_RESULT_H

// Rows of a statement, copied out of the database client on the worker thread.
// A result owns plain strings only, so it can be handed to the game thread,
// stored, copied or dropped without keeping a connection alive.

#include "db_types.h"

#include <base/big_int.h>
#include <teeother/tools/nlohmann_json.h>

#include <cstdint>
#include <optional>
#include <string>
#include <string_view>
#include <vector>

namespace Db
{
	class CResultSet
	{
	public:
		static CResultSet Failure(SError Error);

		// True when the statement ran; an empty result with no rows is still ok.
		bool Ok() const { return m_Error.m_Code == 0 && m_Error.m_Message.empty(); }
		const SError& Error() const { return m_Error; }

		// True when the statement changed at least one row. The check a
		// compare-and-swap write needs: Ok() alone also holds when nothing matched.
		bool Changed() const { return Ok() && m_AffectedRows > 0; }

		// --- rows -----------------------------------------------------------
		// The column getters below read the current row. A result that was never
		// advanced reads its first row, so a single row needs no Next():
		//     if(!Result.HasRows()) return;
		//     const int ID = Result.GetInt("ID");
		// Next() then walks the rows that follow, so reading the first row
		// directly and looping with Next() never visits a row twice.
		bool Next();
		// The current row, 1-based; 0 before the first Next().
		size_t Row() const { return m_Row; }
		size_t RowCount() const { return m_vRows.size(); }
		bool HasRows() const { return !m_vRows.empty(); }
		// Column access by position, for statements like SHOW TABLES whose labels
		// are generated by the server.
		size_t ColumnCount() const { return m_vColumns.size(); }
		std::string GetStringAt(size_t Index) const;

		// --- column values of the current row (the first one by default) --------
		std::string GetString(std::string_view Column) const;
		bool GetBoolean(std::string_view Column) const;
		int GetInt(std::string_view Column) const;
		unsigned int GetUInt(std::string_view Column) const;
		int64_t GetInt64(std::string_view Column) const;
		uint64_t GetUInt64(std::string_view Column) const;
		double GetDouble(std::string_view Column) const;
		BigInt GetBigInt(std::string_view Column) const;
		nlohmann::json GetJson(std::string_view Column) const;

		// --- statement outcome ----------------------------------------------
		size_t AffectedRows() const { return m_AffectedRows; }
		int64_t InsertId() const { return m_InsertId; }

		// --- filling, used by the database clients ---------------------------
		void SetColumns(std::vector<std::string> vColumns);
		void AddRow(std::vector<std::optional<std::string>> vValues);
		void SetAffectedRows(size_t Rows) { m_AffectedRows = Rows; }
		void SetInsertId(int64_t Id) { m_InsertId = Id; }
		void SetError(SError Error) { m_Error = std::move(Error); }

	private:
		// Index of a column, -1 if it does not exist.
		int ColumnIndex(std::string_view Column) const;
		const std::optional<std::string>& ValueAt(int Index) const;

		SError m_Error;
		std::vector<std::string> m_vColumns;
		std::vector<std::vector<std::optional<std::string>>> m_vRows;
		size_t m_Row = 0;          // 0: before the first row (a read takes the first one)
		mutable bool m_Peeked = false; // the first row was read without Next()
		size_t m_AffectedRows = 0;
		int64_t m_InsertId = 0;
	};
}

#endif // ENGINE_SERVER_DB_DB_RESULT_H
